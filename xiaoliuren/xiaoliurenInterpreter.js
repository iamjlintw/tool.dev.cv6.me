    function assertPalaces(palaces) {
        if (!Array.isArray(palaces) || palaces.length !== 3 || !palaces.every(Palaces.isPalace)) {
            throw new TypeError('interpret 需要三個合法宮位名稱');
        }
    }

    /**
     * @param {string[]} palaces 三宮名稱（前、中、後）
     * @param {string} category 分類 id；未知分類視為 general
     */
    function interpret(palaces, category) {
        assertPalaces(palaces);
        const cat = Core.isCategory(category) ? category : 'general';

        const segments = POSITIONS.map((pos, i) => {
            const palace = Palaces.get(palaces[i]);
            return {
                position: pos.id,
                positionLabel: pos.label,
                positionRole: pos.role,
                palace: palace.name,
                keyword: palace.keyword,
                text: POSITION_TEXT[palace.name][pos.id][cat],
            };
        });

        const transitions = [0, 1].map((i) => {
            const from = Palaces.get(palaces[i]).tone;
            const to = Palaces.get(palaces[i + 1]).tone;
            return { from: palaces[i], to: palaces[i + 1], text: TRANSITIONS[`${from}>${to}`] };
        });

        const specials = SPECIALS.filter((s) => s.match(palaces)).map((s) => s.text(palaces));

        const advice = '行動建議：' + Palaces.get(palaces[2]).actionMeaning;

        const paragraphs = [
            segments[0].text + transitions[0].text + segments[1].text + transitions[1].text + segments[2].text,
        ].concat(specials, [advice]);

        return {
            category: cat,
            categoryLabel: Core.categoryLabel(cat),
            palaces: palaces.slice(),
            segments,
            transitions,
            specials,
            advice,
            paragraphs,
            summary: paragraphs.join('\n'),
            caveats: CAVEATS.slice(),
        };
    }

